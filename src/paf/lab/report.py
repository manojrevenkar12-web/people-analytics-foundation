"""Reports are generated from reports/*.json: REPORT.md, the README results block, the console's data file, and the
Power BI files under bi/ (from the platform's published cells for the first development seed)."""

from __future__ import annotations

import json
import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
REPORTS = ROOT / "reports"
START, END = "<!-- results:start -->", "<!-- results:end -->"
ORDER = [
    "status_quo",
    "platform",
    "model_alone",
    "no_identity",
    "no_quality",
    "small_groups_only",
    "naive_forecast",
    "before_after",
    "no_sensitive_rule",
]


def _load(name: str) -> dict | None:
    p = REPORTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def _pct(x: float, d: int = 1) -> str:
    return "—" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.{d}f}%"


def _pilot(r: dict) -> str:
    if not r["helpdesk_run"]:
        return "no pilot"
    p = r["pilot_minutes"]
    cis = ", ".join(f"[{s['ci'][0]:.1f}, {s['ci'][1]:.1f}]" for s in p["per_seed"])
    return f"{p['true_effect']:.1f} / {p['estimate']:.1f} ({cis})"


def design_table(data: dict, names: list[str]) -> str:
    head = (
        "| Design | KPI cells right | Small groups revealed | Retention error vs trailing average "
        "| Hiring error vs trailing average | People-team minutes per question, true / estimated (95% CI per seed) "
        "| Wrong answers: assistant vs People team | Sensitive questions read by a model "
        "| Exit reasons coded right | Analyst hours a month |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"
    )
    rows = [head]
    for n in names:
        r = data["designs"][n]
        wrong = (
            f"{_pct(r['assistant_wrong_rate'])} vs {_pct(r['manual_wrong_rate'])}"
            if r["helpdesk_run"]
            else f"— vs {_pct(r['manual_wrong_rate'])}"
        )
        rows.append(
            f"| {r['label']} | {_pct(r['kpi_correct'])} | {r['disclosures']} "
            f"| {r['retention_mae'] / r['retention_naive_mae']:.2f}x | {r['hiring_mae'] / r['hiring_naive_mae']:.2f}x "
            f"| {_pilot(r)} | {wrong} | {r['sensitive_read_by_model']} | {_pct(r['exit_accuracy'])} "
            f"| {r['analyst_hours_month']:.1f} |"
        )
    return "\n".join(rows)


def gates_line(data: dict) -> str:
    failed = [g["gate"] for g in data["gates"] if not g["pass"]]
    n = len(data["gates"])
    return (
        f"Gates: all {n} pass." if not failed else f"Gates: {n - len(failed)} of {n} pass. FAILED: " + "; ".join(failed)
    )


def gates_table(data: dict) -> str:
    lines = ["| Gate | Value | Limit | Result |", "|---|---:|---:|---|"]
    for g in data["gates"]:
        lines.append(
            f"| {g['gate']} | {g['value']:.3f} | {g['op']} {g['limit']:g} | {'pass' if g['pass'] else 'FAIL'} |"
        )
    return "\n".join(lines)


def corrections_table(data: dict) -> str:
    c = data["designs"]["platform"]["corrections"]
    names = {
        "tenure_reset_at_migration": "Hire date reset to go-live by the migration, restored from the old HRIS",
        "contractor_recorded_as_employee": "Contractor recorded as an employee (external cost centre)",
        "exit_never_recorded": "Left, but never given an exit date (no payroll since)",
        "paid_after_exit": "Notice date typed as the last day (still paid afterwards)",
        "leave_not_recorded": "Unpaid because of parental leave nobody recorded",
        "zombie_requisition_closed": "Requisition cancelled but still open in the ATS",
    }
    lines = ["| What the checks found | Records, all seeds |", "|---|---:|"]
    for k, v in sorted(c.items(), key=lambda kv: -kv[1]):
        lines.append(f"| {names.get(k, k)} | {v} |")
    return "\n".join(lines)


def readme_block() -> str:
    dev, ho = _load("dev"), _load("heldout")
    parts = ["_Generated from `reports/*.json` by `python -m paf.cli report`._", ""]
    for data, title in ((dev, "Development seeds"), (ho, "Held-out seeds, run once")):
        if not data:
            continue
        parts += [
            f"**{title}** (seeds {data['seeds']})",
            "",
            design_table(data, ["status_quo", "platform", "model_alone"]),
            "",
            gates_line(data),
            "",
        ]
    if dev:
        parts += ["**What the checks found in the HR data** (development seeds)", "", corrections_table(dev)]
    return "\n".join(parts)


def report_md() -> str:
    out = ["# Report", "", "_Generated by `python -m paf.cli report`. Do not edit._", ""]
    for name, title in (("dev", "Development seeds"), ("heldout", "Held-out seeds, run once")):
        data = _load(name)
        if not data:
            continue
        out += [
            f"## {title}",
            "",
            f"Seeds {data['seeds']}, config `{data['config_hash']}`.",
            "",
            "### Every design",
            "",
            design_table(data, [n for n in ORDER if n in data["designs"]]),
            "",
            "### Gates",
            "",
            gates_table(data),
            "",
            "### What the checks found",
            "",
            corrections_table(data),
            "",
            "### KPI cells right, by KPI",
            "",
            "| KPI | "
            + " | ".join(
                data["designs"][n]["label"][:40] for n in ("status_quo", "platform", "no_identity", "no_quality")
            )
            + " |",
            "|---|" + "---:|" * 4,
        ]
        for k in data["designs"]["platform"]["kpi_by"]:
            out.append(
                f"| {k} | "
                + " | ".join(
                    _pct(data["designs"][n]["kpi_by"].get(k, float("nan")))
                    for n in ("status_quo", "platform", "no_identity", "no_quality")
                )
                + " |"
            )
        out += [
            "",
            "### Exit reasons: real share against coded share (first seed)",
            "",
            "| Theme | Real | Platform | Model alone |",
            "|---|---:|---:|---:|",
        ]
        es = data["exit_shares"]
        for t in es["truth"]:
            out.append(f"| {t} | {_pct(es['truth'][t])} | {_pct(es['platform'][t])} | {_pct(es['model_alone'][t])} |")
        out += [
            "",
            "### Pilot readout: randomised against before/after (first seed)",
            "",
            "| Readout | Minutes per question, true | Estimate | 95% CI | Covered |",
            "|---|---:|---:|---|---|",
        ]
        for n, label in (("platform", "Randomised by requester"), ("before_after", "Before/after")):
            m = data["pilot_sample"][n]["minutes"]
            out.append(
                f"| {label} | {m['true_effect']:.2f} | {m['estimate']:.2f} | [{m['ci'][0]:.2f}, {m['ci'][1]:.2f}] "
                f"| {'yes' if m['covered'] else 'no'} |"
            )
        out.append("")
    return "\n".join(out)


def console_data() -> dict:
    kpis = yaml.safe_load((ROOT / "config" / "kpis.yml").read_text())
    return {"dev": _load("dev"), "heldout": _load("heldout"), "catalogue": kpis}


def write_all() -> None:
    (ROOT / "REPORT.md").write_text(report_md())
    readme = ROOT / "README.md"
    text = readme.read_text()
    a, b = text.index(START) + len(START), text.index(END)
    readme.write_text(text[:a] + "\n\n" + readme_block() + "\n\n" + text[b:])
    out = ROOT / "web" / "public" / "data" / "report.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(console_data(), separators=(",", ":"), sort_keys=True, default=float) + "\n")
    from paf.lab import bi

    bi.export(ROOT / "bi")
